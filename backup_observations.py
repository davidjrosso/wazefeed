"""Consistent compressed daily backups; retention applies only to these copies."""
import argparse
from contextlib import closing
from datetime import datetime, timezone
import gzip
import os
from pathlib import Path
import re
import shutil
import sqlite3
import tempfile
import uuid

from observation_store import connect_readonly


def backup(database, directory, keep=7):
    if keep < 1:
        raise ValueError('At least one backup must be kept')
    directory = Path(directory)
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    name = 'history-' + datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ') + '-' + uuid.uuid4().hex[:8] + '.sqlite3.gz'
    target = directory / name
    with tempfile.TemporaryDirectory(prefix='.history-backup-', dir=directory) as tmp:
        snapshot = Path(tmp) / 'snapshot.sqlite3'
        compressed = Path(tmp) / 'snapshot.gz'
        with closing(connect_readonly(database)) as source, closing(sqlite3.connect(snapshot)) as destination:
            source.backup(destination)
            if destination.execute('PRAGMA integrity_check').fetchone()[0] != 'ok':
                raise ValueError('Backup integrity check failed')
        with snapshot.open('rb') as source, gzip.open(compressed, 'wb') as destination:
            shutil.copyfileobj(source, destination)
        os.chmod(compressed, 0o600)
        with compressed.open('r+b') as stream:
            os.fsync(stream.fileno())
        os.replace(compressed, target)
    # Delete only files generated by this tool, after the new backup is complete.
    copies = sorted((p for p in directory.iterdir() if p.is_file() and not p.is_symlink()
                     and re.fullmatch(r'history-[0-9]{8}T[0-9]{6}Z-[a-f0-9]{8}\.sqlite3\.gz', p.name)),
                    key=lambda p: (p.stat().st_mtime_ns, p.name))
    # Same-second runs have random suffixes; never remove the backup just made.
    older = [p for p in copies if p != target]
    for path in older[:max(0, len(copies)-keep)]:
        path.unlink()
    return target


def main():
    parser = argparse.ArgumentParser(description='Respaldo comprimido del archivo Waze.')
    parser.add_argument('--database', default='/var/lib/waze-monitor/history.sqlite3')
    parser.add_argument('--directory', default='/var/lib/waze-monitor/backups')
    parser.add_argument('--keep', type=int, default=7)
    args = parser.parse_args()
    path = backup(args.database, args.directory, args.keep)
    print('Waze history backup verified: ' + path.name)


if __name__ == '__main__':
    main()
